namespace Aurora86.Core.Devices.Video;

/// <summary>
/// The register values a VGA ROM loads for each standard mode: miscellaneous
/// output, the five sequencer registers, the twenty-five CRTC registers, the
/// nine graphics controller registers and the twenty-one attribute controller
/// registers. These are the tables every VGA BIOS carries, in the order the
/// hardware indexes them.
///
/// They matter beyond the picture. Software that saves and restores the video
/// state -- Windows' virtual display device does it before it starts a single
/// virtual machine -- reads the lot back through the ports and checks that
/// what it finds describes a working adapter. A CRTC full of zeros does not,
/// and Windows gives up with "video initialization failed".
/// </summary>
public static class VgaRegisterTables
{
    public readonly record struct RegisterSet(
        byte MiscOutput,
        byte[] Sequencer,
        byte[] Crtc,
        byte[] Graphics,
        byte[] Attribute);

    // --- shared fragments -------------------------------------------------

    private static readonly byte[] SeqText = [0x03, 0x00, 0x03, 0x00, 0x02];
    private static readonly byte[] SeqText40 = [0x03, 0x08, 0x03, 0x00, 0x02];
    private static readonly byte[] SeqPlanar = [0x03, 0x01, 0x0F, 0x00, 0x06];
    private static readonly byte[] SeqPlanar40 = [0x03, 0x09, 0x0F, 0x00, 0x06];
    private static readonly byte[] SeqLinear = [0x03, 0x01, 0x0F, 0x00, 0x0E];

    // The CGA modes: all four planes enabled and the odd/even bit clear in
    // the memory mode register, since the interleave the CGA has is between
    // scan lines rather than between planes.
    private static readonly byte[] SeqCga = [0x03, 0x09, 0x03, 0x00, 0x02];

    private static readonly byte[] GcText = [0x00, 0x00, 0x00, 0x00, 0x00, 0x10, 0x0E, 0x0F, 0xFF];
    private static readonly byte[] GcTextMono = [0x00, 0x00, 0x00, 0x00, 0x00, 0x10, 0x0A, 0x0F, 0xFF];
    private static readonly byte[] GcPlanar = [0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x05, 0x0F, 0xFF];
    private static readonly byte[] GcLinear = [0x00, 0x00, 0x00, 0x00, 0x00, 0x40, 0x05, 0x0F, 0xFF];

    /// <summary>
    /// The CGA graphics modes. Register 5 has the odd/even bit set, because
    /// the CGA's interleaved scan lines are exactly that arrangement seen
    /// from the memory side; register 6 selects graphics at 0xB8000, which is
    /// where the CGA lived and where every program written for it looks.
    /// </summary>
    private static readonly byte[] GcCga = [0x00, 0x00, 0x00, 0x00, 0x00, 0x30, 0x0F, 0x0F, 0xFF];

    private static readonly byte[] AttrText =
        [0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x14, 0x07, 0x38, 0x39, 0x3A, 0x3B, 0x3C, 0x3D, 0x3E, 0x3F,
         0x0C, 0x00, 0x0F, 0x08, 0x00];
    private static readonly byte[] AttrTextMono =
        [0x00, 0x08, 0x08, 0x08, 0x08, 0x08, 0x08, 0x08, 0x10, 0x18, 0x18, 0x18, 0x18, 0x18, 0x18, 0x18,
         0x0E, 0x00, 0x0F, 0x08, 0x00];
    private static readonly byte[] AttrEga16 =
        [0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17,
         0x01, 0x00, 0x0F, 0x00, 0x00];
    private static readonly byte[] AttrVga16 =
        [0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x14, 0x07, 0x38, 0x39, 0x3A, 0x3B, 0x3C, 0x3D, 0x3E, 0x3F,
         0x01, 0x00, 0x0F, 0x00, 0x00];
    private static readonly byte[] AttrMono350 =
        [0x00, 0x08, 0x00, 0x00, 0x18, 0x18, 0x00, 0x00, 0x00, 0x08, 0x00, 0x00, 0x00, 0x18, 0x00, 0x00,
         0x0B, 0x00, 0x05, 0x00, 0x00];
    private static readonly byte[] AttrMono480 =
        [0x00, 0x3F, 0x3F, 0x3F, 0x3F, 0x3F, 0x3F, 0x3F, 0x3F, 0x3F, 0x3F, 0x3F, 0x3F, 0x3F, 0x3F, 0x3F,
         0x01, 0x00, 0x0F, 0x00, 0x00];
    private static readonly byte[] AttrLinear =
        [0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x0E, 0x0F,
         0x41, 0x00, 0x0F, 0x00, 0x00];

    // CRTC: 400-line text (9-dot cells, 80 and 40 columns), 200-line graphics
    // (80 and 40 columns), 350-line and 480-line 16-colour, and mode 13h.
    private static readonly byte[] CrtcText80 =
        [0x5F, 0x4F, 0x50, 0x82, 0x55, 0x81, 0xBF, 0x1F, 0x00, 0x4F, 0x0D, 0x0E, 0x00, 0x00, 0x00, 0x00,
         0x9C, 0x8E, 0x8F, 0x28, 0x1F, 0x96, 0xB9, 0xA3, 0xFF];
    private static readonly byte[] CrtcText40 =
        [0x2D, 0x27, 0x28, 0x90, 0x2B, 0xA0, 0xBF, 0x1F, 0x00, 0x4F, 0x0D, 0x0E, 0x00, 0x00, 0x00, 0x00,
         0x9C, 0x8E, 0x8F, 0x14, 0x1F, 0x96, 0xB9, 0xA3, 0xFF];
    private static readonly byte[] CrtcTextMono =
        [0x5F, 0x4F, 0x50, 0x82, 0x55, 0x81, 0xBF, 0x1F, 0x00, 0x4F, 0x0D, 0x0E, 0x00, 0x00, 0x00, 0x00,
         0x9C, 0x8E, 0x8F, 0x28, 0x0F, 0x96, 0xB9, 0xA3, 0xFF];
    private static readonly byte[] Crtc200x80 =
        [0x5F, 0x4F, 0x50, 0x82, 0x54, 0x80, 0xBF, 0x1F, 0x00, 0xC0, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
         0x9C, 0x8E, 0x8F, 0x28, 0x00, 0x96, 0xB9, 0xE3, 0xFF];
    private static readonly byte[] Crtc200x40 =
        [0x2D, 0x27, 0x28, 0x90, 0x2B, 0x80, 0xBF, 0x1F, 0x00, 0xC0, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
         0x9C, 0x8E, 0x8F, 0x14, 0x00, 0x96, 0xB9, 0xE3, 0xFF];
    private static readonly byte[] Crtc350 =
        [0x5F, 0x4F, 0x50, 0x82, 0x54, 0x80, 0xBF, 0x1F, 0x00, 0x40, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
         0x83, 0x85, 0x5D, 0x28, 0x0F, 0x63, 0xBA, 0xE3, 0xFF];
    private static readonly byte[] Crtc480 =
        [0x5F, 0x4F, 0x50, 0x82, 0x54, 0x80, 0x0B, 0x3E, 0x00, 0x40, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
         0xEA, 0x8C, 0xDF, 0x28, 0x00, 0xE7, 0x04, 0xE3, 0xFF];
    // 320x200 and 640x200 in CGA terms. The interesting field is 0x09: the
    // maximum scan line register with its doubling bit set, because 200 lines
    // are shown on a 400-line raster and every line is drawn twice.
    private static readonly byte[] CrtcCga =
        [0x2D, 0x27, 0x28, 0x90, 0x2B, 0x80, 0xBF, 0x1F, 0x00, 0xC1, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
         0x9C, 0x8E, 0x8F, 0x14, 0x00, 0x96, 0xB9, 0xA2, 0xFF];

    private static readonly byte[] CrtcCga640 =
        [0x5F, 0x4F, 0x50, 0x82, 0x54, 0x80, 0xBF, 0x1F, 0x00, 0xC1, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
         0x9C, 0x8E, 0x8F, 0x28, 0x00, 0x96, 0xB9, 0xC2, 0xFF];

    private static readonly byte[] CrtcLinear =
        [0x5F, 0x4F, 0x50, 0x82, 0x54, 0x80, 0xBF, 0x1F, 0x00, 0x41, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
         0x9C, 0x8E, 0x8F, 0x28, 0x40, 0x96, 0xB9, 0xA3, 0xFF];

    /// <summary>
    /// The set for a mode number, or the 80x25 colour text set for one we do
    /// not know -- that is also the mode the BIOS falls back to.
    /// </summary>
    public static RegisterSet For(byte mode) => mode switch
    {
        0x00 or 0x01 => new(0x67, SeqText40, CrtcText40, GcText, AttrText),
        0x07 => new(0x66, SeqText, CrtcTextMono, GcTextMono, AttrTextMono),
        0x0D => new(0x63, SeqPlanar40, Crtc200x40, GcPlanar, AttrEga16),
        0x0E => new(0x63, SeqPlanar, Crtc200x80, GcPlanar, AttrEga16),
        0x0F => new(0xA2, SeqPlanar, Crtc350, GcPlanar, AttrMono350),
        0x10 => new(0xA3, SeqPlanar, Crtc350, GcPlanar, AttrVga16),
        0x11 => new(0xE3, SeqPlanar, Crtc480, GcPlanar, AttrMono480),
        0x12 => new(0xE3, SeqPlanar, Crtc480, GcPlanar, AttrVga16),
        0x13 => new(0x63, SeqLinear, CrtcLinear, GcLinear, AttrLinear),

        // The CGA graphics modes, kept because a great deal of software
        // predates everything that replaced them. Mode 5 is mode 4 with the
        // colour burst off: on a television that meant grey instead of
        // colour, on a monitor it meant nothing at all, and the registers are
        // the same either way.
        0x04 or 0x05 => new(0x63, SeqCga, CrtcCga, GcCga, AttrEga16),
        0x06 => new(0x63, SeqCga, CrtcCga640, GcCga, AttrEga16),
        _ => new(0x67, SeqText, CrtcText80, GcText, AttrText),
    };
}
